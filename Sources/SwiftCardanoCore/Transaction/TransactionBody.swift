            dictionary[key(CodingKeys.treasuryDonation)] = try treasuryDonation.toPrimitive()
        }

        return .orderedDict(inWrittenOrder(dictionary))
    }

    /// Puts the fields back in the order this body was written in, with any it
    /// gained since following in numeric order.
    private func inWrittenOrder(
        _ fields: OrderedDictionary<Primitive, Primitive>
    ) -> OrderedDictionary<Primitive, Primitive> {
        guard !writtenFieldOrder.isEmpty else { return fields }
        var ordered = OrderedDictionary<Primitive, Primitive>()
        for number in writtenFieldOrder {
            let key = Primitive.uint(UInt64(number))
            if let value = fields[key] { ordered[key] = value }
        }
        for (key, value) in fields where ordered[key] == nil {
            ordered[key] = value
        }
        return ordered
    }

    // MARK: - JSONSerializable

    public static func fromDict(_ dict: Primitive) throws -> TransactionBody {
        guard case .orderedDict(let orderedDict) = dict else {
            throw CardanoCoreError.deserializeError("Invalid TransactionBody dict format")
        }
        // Required fields
        guard let inputsPrimitive = orderedDict[.string(CodingKeys.inputs.stringValue)] else {
            throw CardanoCoreError.deserializeError("Missing inputs in TransactionBody")
        }
        let inputs = try ListOrOrderedSet<TransactionInput>.fromDict(inputsPrimitive)

        guard let outputsPrimitive = orderedDict[.string(CodingKeys.outputs.stringValue)] else {
            throw CardanoCoreError.deserializeError("Missing or invalid outputs in TransactionBody")
        }
        let outputsList: [Primitive]
        switch outputsPrimitive {
        case .list(let l): outputsList = l
        case .indefiniteList(let l): outputsList = Array(l)
        default:
            throw CardanoCoreError.deserializeError("Missing or invalid outputs in TransactionBody")
        }
        let outputs = try outputsList.map { try TransactionOutput.fromDict($0) }

        guard let feePrimitive = orderedDict[.string(CodingKeys.fee.stringValue)] else {
            throw CardanoCoreError.deserializeError("Missing or invalid fee in TransactionBody")
        }
