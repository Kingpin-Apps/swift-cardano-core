    public static var preservesEncoding: Bool { true }

    public init(from primitive: Primitive) throws {
        // Bytes kept as written, from this type's own `toPrimitive()`: read
        // them again, keeping them.
        if case .cborSimpleValue(.encoded(let bytes)) = primitive {
            self = try Self.fromCBOR(data: bytes)
            return
        }
        var written: OrderedDictionary<Primitive, Primitive> = [:]

        switch primitive {
        case .dict(let dict):
            written.merge(dict) { (_, new) in new }
        case .orderedDict(let orderedDict), .indefiniteDictionary(let orderedDict):
            written = orderedDict
        default:
            throw CardanoCoreError.deserializeError("Invalid TransactionBody type: \(primitive)")
        }
        var primitiveDict = OrderedDictionary<Primitive, Primitive>()
        for (key, value) in written {
            let field = try key.normalized()
            primitiveDict[field] = field == .uint(UInt64(CodingKeys.certificates.rawValue))
                ? value : try value.normalized()
        }

        func key(_ key: CodingKeys) -> Primitive { .uint(UInt64(key.rawValue)) }

        // Required fields
        guard let inputsPrimitive = primitiveDict[key(.inputs)] else {
            throw CardanoCoreError.deserializeError("TransactionBody inputs are required")
        }
        let inputs = try ListOrOrderedSet<TransactionInput>(from: inputsPrimitive)

        guard let outputsPrimitive = primitiveDict[key(.outputs)] else {
            throw CardanoCoreError.deserializeError("TransactionBody outputs are required")
        }
        let outputs: [TransactionOutput]
        switch outputsPrimitive {
        case .list(let outputsList):
            outputs = try outputsList.map { try TransactionOutput(from: $0) }
        case .indefiniteList(let outputsList):
            outputs = try outputsList.map { try TransactionOutput(from: $0) }
        default:
            throw CardanoCoreError.deserializeError("TransactionBody outputs must be an array")
        }

        guard let feePrimitive = primitiveDict[key(.fee)] else {
            throw CardanoCoreError.deserializeError("TransactionBody fee is required")
        }
        let fee: Coin = try feePrimitive.integer("TransactionBody fee")

        // Optional fields
        let ttl: SlotNumber? = try primitiveDict[key(.ttl)].map {
            try $0.integer("TransactionBody ttl")
        }

        let certificates: ListOrNonEmptyOrderedSet<Certificate>?
        if let certificatesPrimitive = primitiveDict[key(.certificates)] {
            certificates = try ListOrNonEmptyOrderedSet<Certificate>(from: certificatesPrimitive)
        } else {
            certificates = nil
        }

        let withdrawals: Withdrawals?
        if let withdrawalsPrimitive = primitiveDict[key(.withdrawals)] {
            withdrawals = try Withdrawals(from: withdrawalsPrimitive)
        } else {
            withdrawals = nil
        }

        let update: Update?
        if let updatePrimitive = primitiveDict[key(.update)] {
            update = try Update(from: updatePrimitive)
        } else {
            update = nil
        }

        let auxiliaryDataHash: AuxiliaryDataHash?
        if let auxiliaryDataHashPrimitive = primitiveDict[key(.auxiliaryDataHash)] {
            auxiliaryDataHash = try AuxiliaryDataHash(from: auxiliaryDataHashPrimitive)
        } else {
            auxiliaryDataHash = nil
        }

        let validityStart: SlotNumber? = try primitiveDict[key(.validityStart)].map {
            try $0.integer("TransactionBody validityStart")
        }

        let mint: MultiAsset?
        if let mintPrimitive = primitiveDict[key(.mint)] {
            // The mint field's amounts are signed 64-bit integers
            // (`DecCBOR MultiAsset`), and from Conway it may not be empty
            // (`emptyFailure "Mint" "non-empty"`,
            // `eras/conway/impl/src/Cardano/Ledger/Conway/TxBody.hs`).
            let decoded = try MultiAsset(from: mintPrimitive, amounts: .mint)
            if Era.decodingRules >= .conway, decoded.isEmpty {
                throw CardanoCoreError.deserializeError("TransactionBody: the mint field may not be empty")
            }
            mint = decoded
        } else {
            mint = nil
        }

        let scriptDataHash: ScriptDataHash?
        if let scriptDataHashPrimitive = primitiveDict[key(.scriptDataHash)] {
            scriptDataHash = try ScriptDataHash(from: scriptDataHashPrimitive)
        } else {
            scriptDataHash = nil
        }

        let collateral: ListOrNonEmptyOrderedSet<TransactionInput>?
        if let collateralPrimitive = primitiveDict[key(.collateral)] {
            collateral = try ListOrNonEmptyOrderedSet<TransactionInput>(from: collateralPrimitive)
        } else {
            collateral = nil
        }

        let requiredSigners: ListOrNonEmptyOrderedSet<VerificationKeyHash>?
        if let requiredSignersPrimitive = primitiveDict[key(.requiredSigners)] {
            requiredSigners = try ListOrNonEmptyOrderedSet<VerificationKeyHash>(
                from: requiredSignersPrimitive)
        } else {
            requiredSigners = nil
        }

        // network_id = 0 / 1
        let networkId: Int? = try primitiveDict[key(.networkId)].map {
            let value: Int = try $0.integer("TransactionBody networkId")
            guard value == 0 || value == 1 else {
                throw CardanoCoreError.deserializeError("TransactionBody networkId must be 0 or 1, got \(value)")
            }
            return value
        }

        let collateralReturn: TransactionOutput?
        if let collateralReturnPrimitive = primitiveDict[key(.collateralReturn)] {
            collateralReturn = try TransactionOutput(from: collateralReturnPrimitive)
        } else {
            collateralReturn = nil
        }

        let totalCollateral: Coin? = try primitiveDict[key(.totalCollateral)].map {
            try $0.integer("TransactionBody totalCollateral")
        }

        let referenceInputs: ListOrNonEmptyOrderedSet<TransactionInput>?
        if let referenceInputsPrimitive = primitiveDict[key(.referenceInputs)] {
            referenceInputs = try ListOrNonEmptyOrderedSet<TransactionInput>(
                from: referenceInputsPrimitive)
        } else {
            referenceInputs = nil
        }

        let votingProcedures: VotingProcedures?
        if let votingProceduresPrimitive = primitiveDict[key(.votingProcedures)] {
            votingProcedures = try VotingProcedures(from: votingProceduresPrimitive)
        } else {
            votingProcedures = nil
        }

        let proposalProcedures: ProposalProcedures?
        if let proposalProceduresPrimitive = primitiveDict[key(.proposalProcedures)] {
            proposalProcedures = try ProposalProcedures(from: proposalProceduresPrimitive)
        } else {
            proposalProcedures = nil
        }

        let currentTreasuryAmount: Coin? = try primitiveDict[key(.currentTreasuryAmount)].map {
            try $0.integer("TransactionBody currentTreasuryAmount")
        }

        let treasuryDonation: PositiveCoin?
        if let treasuryDonationPrimitive = primitiveDict[key(.treasuryDonation)] {
            treasuryDonation = try PositiveCoin(from: treasuryDonationPrimitive)
        } else {
            treasuryDonation = nil
        }

        self.init(
            inputs: inputs,
            outputs: outputs,
            fee: fee,
            ttl: ttl,
            certificates: certificates,
            withdrawals: withdrawals,
            update: update,
            auxiliaryDataHash: auxiliaryDataHash,
            validityStart: validityStart,
            mint: mint,
            scriptDataHash: scriptDataHash,
            collateral: collateral,
            requiredSigners: requiredSigners,
            networkId: networkId,
            collateralReturn: collateralReturn,
            totalCollateral: totalCollateral,
            referenceInputs: referenceInputs,
            votingProcedures: votingProcedures,
            proposalProcedures: proposalProcedures,
            currentTreasuryAmount: currentTreasuryAmount,
            treasuryDonation: treasuryDonation
        )
        // Remember how the fields were laid out, so re-encoding this body
        // reproduces the bytes it was read from — and with them its hash.
        self.writtenFieldOrder = try primitiveDict.keys.map {
            let number: Int = try $0.integer("TransactionBody field")
            guard CodingKeys(rawValue: number) != nil else {
                // The ledger reads a body as a sparse record and rejects a
                // field it does not know.
                throw CardanoCoreError.deserializeError("Unknown TransactionBody field \(number)")
            }
            return number
        }
        if let era = Era.decoding {
            try LedgerFields.check(
                writtenFieldOrder.map { UInt64($0) }, allowed: LedgerFields.transactionBody(era),
                era: era, in: "TransactionBody")
        }
    }

    /// The bytes this body was decoded from while it is unchanged — so that
    /// encoding it, alone or inside a transaction, gives what was written and
    /// keeps the id — otherwise its fields.
    public func toPrimitive() throws -> Primitive {
        if let originalCBOR {
            return .cborSimpleValue(.encoded(originalCBOR))
        }
        var dictionary: OrderedDictionary<Primitive, Primitive> = [:]

        func key(_ key: CodingKeys) -> Primitive {
            return .uint(UInt64(key.rawValue))
        }

        // Required fields
        dictionary[key(CodingKeys.inputs)] = try inputs.toPrimitive()
        dictionary[key(CodingKeys.outputs)] =
            .list(try outputs.map { try $0.toPrimitive() })
        dictionary[key(CodingKeys.fee)] = .uint(UInt64(fee))

        // Optional fields
        if let ttl = ttl {
            dictionary[key(CodingKeys.ttl)] = .uint(UInt64(ttl))
        }
        if let certificates = certificates {
            dictionary[key(CodingKeys.certificates)] = try certificates.toPrimitive()
        }
        if let withdrawals = withdrawals {
            dictionary[key(CodingKeys.withdrawals)] = try withdrawals.toPrimitive()
        }
        if let update = update {
            dictionary[key(CodingKeys.update)] = try update.toPrimitive()
        }
        if let auxiliaryDataHash = auxiliaryDataHash {
            dictionary[key(CodingKeys.auxiliaryDataHash)] = auxiliaryDataHash.toPrimitive()
        }
        if let validityStart = validityStart {
            dictionary[key(CodingKeys.validityStart)] =
                .uint(UInt64(validityStart))
        }
        if let mint = mint {
            dictionary[key(CodingKeys.mint)] = mint.toPrimitive()
        }
        if let scriptDataHash = scriptDataHash {
            dictionary[key(CodingKeys.scriptDataHash)] = scriptDataHash.toPrimitive()
        }
        if let collateral = collateral {
            dictionary[key(CodingKeys.collateral)] = try collateral.toPrimitive()
        }
        if let requiredSigners = requiredSigners {
            dictionary[key(CodingKeys.requiredSigners)] = try requiredSigners.toPrimitive()
        }
        if let networkId = networkId {
            dictionary[key(CodingKeys.networkId)] = Primitive.integer(networkId)
        }
        if let collateralReturn = collateralReturn {
            dictionary[key(CodingKeys.collateralReturn)] = try collateralReturn.toPrimitive()
        }
        if let totalCollateral = totalCollateral {
            dictionary[key(CodingKeys.totalCollateral)] =
                .uint(UInt64(totalCollateral))
        }
        if let referenceInputs = referenceInputs {
            dictionary[key(CodingKeys.referenceInputs)] = try referenceInputs.toPrimitive()
        }
        if let votingProcedures = votingProcedures {
            dictionary[key(CodingKeys.votingProcedures)] = try votingProcedures.toPrimitive()
        }
        if let proposalProcedures = proposalProcedures {
            dictionary[key(CodingKeys.proposalProcedures)] = try proposalProcedures.toPrimitive()
        }
        if let currentTreasuryAmount = currentTreasuryAmount {
            dictionary[key(CodingKeys.currentTreasuryAmount)] =
